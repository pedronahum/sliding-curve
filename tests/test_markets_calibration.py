import numpy as np
import jax
import jax.numpy as jnp

from slidingcurve import Model, bachelier as bl, calibration, markets, pricing as pr, volscale


def test_joshi_curve_reprices_forwards():
    mkt = markets.joshi_2014()
    t = 0.5 * np.arange(42)
    df = np.asarray(mkt.curve.discount(jnp.asarray(t)))
    np.testing.assert_allclose((df[:-1] / df[1:] - 1.0) / 0.5, mkt.forwards, atol=1e-13)
    np.testing.assert_allclose(mkt.forwards[[0, 3, 40]], [0.008, 0.014, 0.088])


def test_joshi_caplet_vol_is_root_mean_square_abcd():
    """One-period swaption = caplet: the frozen-weights formula is exact and
    reduces to the integrated abcd variance."""
    mkt = markets.joshi_2014()
    T = 5.0
    s = np.linspace(0.0, T, 200001)
    v2 = np.trapezoid(((mkt.a + mkt.b * s) * np.exp(-mkt.c * s) + mkt.d) ** 2, s) / T
    np.testing.assert_allclose(mkt.swaption_vol(10, 1), np.sqrt(v2), rtol=1e-8)


def test_joshi_smile_is_upward_sloping_in_normal_vol():
    q = markets.joshi_2014().quotes(10.0, 5.0, [-0.01, 0.0, 0.01])
    assert np.all(np.diff(q.normal_vols) > 0)


def test_calibration_recovers_known_parameters(ns_curve):
    """Quotes generated by the model itself are fitted back exactly when the
    same random numbers are used: checks the optimiser and the autodiff Jacobian."""
    truth = Model(kappa=0.03, delta=5.0, sigma=0.012, b=0.4)
    swp = pr.Swaption.regular(10.0, 5.0)
    key = jax.random.PRNGKey(11)
    ybar = lambda t: volscale.ybar_zeroth(ns_curve, 5.0, t)
    fwd, ann = float(pr.forward_swap_rate(ns_curve, swp)), float(pr.annuity(ns_curve, swp))
    strikes = fwd + np.array([-0.01, -0.005, 0.0, 0.005, 0.01])
    prices = np.asarray(pr.swaption_prices(truth, ns_curve, swp, strikes, ybar, key, n_paths=2**13)[0])
    q = markets.Quotes(swp, fwd, ann, strikes, prices,
                       bl.implied_normal_vol(prices / ann, fwd, strikes, swp.expiry))
    fit = calibration.calibrate(truth._replace(sigma=0.008, b=0.0), ns_curve, q,
                                free=("sigma", "b"), ybar_fn=ybar, key=key, n_paths=2**13)
    assert fit.success
    np.testing.assert_allclose([fit.model.sigma, fit.model.b], [0.012, 0.4], rtol=1e-4)
    assert np.max(np.abs(fit.vol_errors_bp)) < 1e-3


def test_bootstrap_scaling_holds_atm_better_than_zeroth(ns_curve):
    """The point of Appendix C.3: with the bootstrap, moving the skew from 0 to
    1 moves the at-the-money volatility far less than with forward centring."""
    swp = pr.Swaption.caplet(20.0, 5.0)
    fwd = np.array([float(pr.forward_swap_rate(ns_curve, swp))])
    key = jax.random.PRNGKey(5)
    base = Model(kappa=0.03, delta=5.0, sigma=0.01)
    grid = np.arange(1.0, 21.0)

    def atm_move(ybar):
        p0, p1 = (np.asarray(pr.swaption_prices(base._replace(b=b), ns_curve, swp, fwd, ybar,
                                                key, n_paths=2**14)[0])[0] for b in (0.0, 1.0))
        return abs(p1 / p0 - 1.0)           # ATM price is proportional to normal vol

    zeroth = atm_move(lambda t: volscale.ybar_zeroth(ns_curve, 5.0, t))
    boot = atm_move(volscale.bootstrap_fn(ns_curve, base, grid))
    assert boot < 0.05 < zeroth
